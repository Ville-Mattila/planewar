"""Shared reader/writer for the locale pipeline (docs/06 s11, R0 C2-33). Pure stdlib.

Source of truth: godot/content/locale/src/<domain>.csv with columns id,en,fi,max_len,context,note.
English-only drop-in: godot/content/locale/en.json (flat id -> text), merged into the English column.
Plural rows: `id#one` and `id#other` (PO msgid_plural, two forms for en and fi).
"""

from __future__ import annotations

import csv
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
LOCALE_DIR = REPO / "godot" / "content" / "locale"
COLUMNS = ["id", "en", "fi", "max_len", "context", "note"]
LANGS = ("en", "fi")
DEFAULT_MAX_FACTOR = 1.4
PSEUDO_EXPANSION = 1.4
PLACEHOLDER_RE = re.compile(r"\{[a-z_][a-z0-9_]*(?::[a-z0-9_]+)?\}")
ID_RE = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z0-9_]+)+(#(one|other))?$")
PLURAL_FORMS = ("one", "other")
ACCENTS = {"a": "\u00e5", "e": "\u00e9", "i": "\u00ee", "o": "\u00f8", "u": "\u00fc", "c": "\u00e7", "n": "\u00f1",
           "A": "\u00c5", "E": "\u00c9", "I": "\u00ce", "O": "\u00d8", "U": "\u00dc"}


@dataclass
class Row:
    id: str
    en: str
    fi: str
    max_len: str
    context: str
    note: str
    source: str  # domain (file stem) or "en.json"

    def text(self, lang: str) -> str:
        return self.en if lang == "en" else self.fi


@dataclass
class Table:
    rows: list[Row] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)


def placeholders(text: str) -> set[str]:
    return set(PLACEHOLDER_RE.findall(text))


def load_csv(path: Path, table: Table) -> None:
    """Appends the rows of one domain CSV; shape problems go to table.errors."""
    with path.open(encoding="utf-8", newline="") as fh:
        reader = csv.reader(fh)
        header = next(reader, None)
        if header != COLUMNS:
            table.errors.append(f"{path.name}: header must be {','.join(COLUMNS)}, got {header}")
            return
        for n, raw in enumerate(reader, start=2):
            if not raw:
                continue
            if len(raw) != len(COLUMNS):
                table.errors.append(f"{path.name}:{n}: expected {len(COLUMNS)} columns, got {len(raw)}")
                continue
            table.rows.append(Row(raw[0], raw[1], raw[2], raw[3], raw[4], raw[5], path.stem))


def load_en_json(path: Path, table: Table) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    for key, text in data.items():
        table.rows.append(Row(key, str(text), "", "", "", "", path.name))


def load_table(locale_dir: Path = LOCALE_DIR) -> Table:
    table = Table()
    for path in sorted((locale_dir / "src").glob("*.csv")):
        load_csv(path, table)
    en_json = locale_dir / "en.json"
    if en_json.exists():
        load_en_json(en_json, table)
    return table


def po_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def po_unescape(text: str) -> str:
    out: list[str] = []
    i = 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            out.append({"n": "\n", "t": "\t"}.get(text[i + 1], text[i + 1]))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def group_plurals(rows: list[Row]) -> list[tuple[str, list[Row]]]:
    """Groups rows into PO entries keyed by the base id, sorted by id."""
    groups: dict[str, list[Row]] = {}
    for r in rows:
        groups.setdefault(r.id.split("#", 1)[0], []).append(r)
    return [(base, groups[base]) for base in sorted(groups)]


def pseudolocalize(text: str) -> str:
    """Accents letters outside placeholders, pads to 1.4x with '~', brackets the result (06 s11)."""
    out: list[str] = []
    pos = 0
    for m in PLACEHOLDER_RE.finditer(text):
        out.append("".join(ACCENTS.get(c, c) for c in text[pos:m.start()]))
        out.append(m.group(0))
        pos = m.end()
    out.append("".join(ACCENTS.get(c, c) for c in text[pos:]))
    pad = max(0, int(len(text) * PSEUDO_EXPANSION) - len(text))
    return "[" + "".join(out) + "~" * pad + "]"


def _entry_text(row: Row, lang: str, pseudo: bool) -> str:
    return pseudolocalize(row.en) if pseudo else row.text(lang)


def render_po(table: Table, lang: str, pseudo: bool = False) -> str:
    """One PO file. Untranslated msgstr stays empty; Godot then uses the fallback locale (en)."""
    code = "en_XA" if pseudo else lang
    lines = [
        "# Generated by tools/locale/build_po.py from godot/content/locale. Do not edit.",
        'msgid ""', 'msgstr ""',
        f'"Language: {code}\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"',
        "",
    ]
    for base, rows in group_plurals(table.rows):
        lines += [f'msgid "{po_escape(base)}"']
        if any("#" in r.id for r in rows):
            ordered = sorted(rows, key=lambda r: PLURAL_FORMS.index(r.id.split("#", 1)[1]))
            lines.append(f'msgid_plural "{po_escape(base)}"')
            lines += [f'msgstr[{n}] "{po_escape(_entry_text(r, lang, pseudo))}"' for n, r in enumerate(ordered)]
        else:
            lines.append(f'msgstr "{po_escape(_entry_text(rows[0], lang, pseudo))}"')
        lines.append("")
    return "\n".join(lines)


def _quoted(line: str) -> str:
    return po_unescape(line[line.index('"') + 1:line.rindex('"')])


def parse_po(text: str) -> dict[str, list[str]]:
    """PO -> {msgid: [msgstr] or [form0, form1]}. The header entry (empty msgid) is dropped."""
    entries: dict[str, list[str]] = {}
    msgid = ""
    strs: dict[int, str] = {}
    cur = ""
    cur_idx = 0
    for raw in text.splitlines() + ['msgid ""']:  # sentinel flushes the last entry
        line = raw.strip()
        if line.startswith("msgid_plural"):
            cur = "plural"
        elif line.startswith("msgid "):
            if msgid and strs:
                entries[msgid] = [strs[k] for k in sorted(strs)]
            msgid, strs, cur = _quoted(line), {}, "id"
        elif line.startswith("msgstr["):
            cur_idx = int(line[7:line.index("]")])
            strs[cur_idx] = _quoted(line)
            cur = "str"
        elif line.startswith("msgstr "):
            cur_idx = 0
            strs[0] = _quoted(line)
            cur = "str"
        elif line.startswith('"'):
            part = po_unescape(line[1:-1])
            if cur == "id":
                msgid += part
            elif cur == "str":
                strs[cur_idx] += part
    return entries


def write_csv(path: Path, rows: list[Row]) -> None:
    with path.open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(COLUMNS)
        for r in rows:
            w.writerow([r.id, r.en, r.fi, r.max_len, r.context, r.note])
