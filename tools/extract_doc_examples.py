#!/usr/bin/env python3
"""Extract every fenced ```json block in docs/02-08 into docs/examples/<NN>/<slug>-<index>.json.

Stdlib only. Each block is written byte-for-byte as it appears in the doc (no edits, no
re-serialisation), so an invalid block stays invalid and is reported, never silently fixed.
JSON cannot carry comments, so the source of every file (doc, line, nearest heading) goes to
docs/examples/INDEX.md instead.

Usage:
    python tools/extract_doc_examples.py            # regenerate docs/examples/
    python tools/extract_doc_examples.py --check    # exit 1 if the committed output is stale

Exit codes: 0 ok, 1 stale output (--check only), 2 I/O error.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
EXAMPLES = DOCS / "examples"
DOC_GLOB = re.compile(r"^0[2-8]-.+\.md$")
FENCE = re.compile(r"^\s*(`{3,})\s*(.*?)\s*$")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")


@dataclass
class Block:
    doc: str          # file name, e.g. 02-game-design.md
    prefix: str       # "02"
    line: int         # 1-based line of the opening fence
    heading: str      # nearest preceding heading text ("" if none)
    index: int        # 1-based index within the doc
    body: str         # raw block content, without fence lines
    slug: str = ""
    rel_path: str = ""

    @property
    def valid(self) -> bool:
        try:
            json.loads(self.body)
            return True
        except ValueError:
            return False


def slugify(text: str, limit: int = 60) -> str:
    norm = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-z0-9]+", "-", norm.lower()).strip("-")
    slug = slug[:limit].rstrip("-")
    return slug or "section"


def extract(doc_path: Path) -> list[Block]:
    """Return the json fenced blocks of one doc, in document order."""
    lines = doc_path.read_text(encoding="utf-8").splitlines()
    blocks: list[Block] = []
    heading = ""
    in_fence = False
    fence_marker = ""
    fence_lang = ""
    fence_line = 0
    body: list[str] = []
    for lineno, raw in enumerate(lines, start=1):
        m = FENCE.match(raw)
        if in_fence:
            # A closing fence is the same marker (or longer) with no info string.
            if m and m.group(1).startswith(fence_marker) and m.group(2) == "":
                if fence_lang.lower().startswith("json"):
                    blocks.append(Block(
                        doc=doc_path.name,
                        prefix=doc_path.name[:2],
                        line=fence_line,
                        heading=heading,
                        index=len(blocks) + 1,
                        body="\n".join(body) + "\n",
                    ))
                in_fence = False
                body = []
            else:
                body.append(raw)
            continue
        if m:
            in_fence = True
            fence_marker = m.group(1)
            fence_lang = m.group(2)
            fence_line = lineno
            body = []
            continue
        h = HEADING.match(raw)
        if h:
            heading = h.group(2)
    if in_fence:
        raise SystemExit(f"{doc_path.name}: unclosed code fence at line {fence_line}")
    return blocks


def collect() -> list[Block]:
    out: list[Block] = []
    for doc_path in sorted(DOCS.glob("*.md")):
        if not DOC_GLOB.match(doc_path.name):
            continue
        blocks = extract(doc_path)
        for b in blocks:
            b.slug = slugify(b.heading)
            b.rel_path = f"{b.prefix}/{b.slug}-{b.index:02d}.json"
        out.extend(blocks)
    return out


def render_index(blocks: list[Block]) -> str:
    rows = [
        "# Doc JSON examples: index",
        "",
        "Generated by `tools/extract_doc_examples.py` from the fenced ```json blocks of docs 02-08.",
        "Do not edit by hand; regenerate with the script. JSON cannot carry comments, so the source",
        "of each file is recorded here.",
        "",
        "| File | Source doc | Line | Nearest heading | Parses as JSON |",
        "|---|---|---|---|---|",
    ]
    for b in blocks:
        heading = b.heading.replace("|", "\\|") or "(none)"
        rows.append(
            f"| `{b.rel_path}` | `docs/{b.doc}` | {b.line} | {heading} | {'yes' if b.valid else 'NO'} |"
        )
    rows.append("")
    return "\n".join(rows)


def write_all(blocks: list[Block]) -> None:
    if EXAMPLES.exists():
        for old in EXAMPLES.glob("0[2-8]/*.json"):
            old.unlink()
    for b in blocks:
        target = EXAMPLES / b.rel_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(b.body, encoding="utf-8", newline="\n")
    (EXAMPLES / "INDEX.md").write_text(render_index(blocks), encoding="utf-8", newline="\n")


def check(blocks: list[Block]) -> bool:
    expected = {b.rel_path: b.body for b in blocks}
    ok = True
    for rel, body in expected.items():
        p = EXAMPLES / rel
        if not p.exists() or p.read_text(encoding="utf-8") != body:
            print(f"stale or missing: docs/examples/{rel}")
            ok = False
    for old in EXAMPLES.glob("0[2-8]/*.json"):
        rel = old.relative_to(EXAMPLES).as_posix()
        if rel not in expected:
            print(f"unexpected file: docs/examples/{rel}")
            ok = False
    index = EXAMPLES / "INDEX.md"
    if not index.exists() or index.read_text(encoding="utf-8") != render_index(blocks):
        print("stale: docs/examples/INDEX.md")
        ok = False
    return ok


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if committed output is stale")
    args = ap.parse_args(argv)

    blocks = collect()
    if args.check:
        if check(blocks):
            print(f"docs/examples up to date ({len(blocks)} blocks)")
            return 0
        return 1

    write_all(blocks)
    valid = sum(b.valid for b in blocks)
    print(f"wrote {len(blocks)} blocks to docs/examples/ ({valid} parse as JSON, {len(blocks) - valid} do not)")
    for b in blocks:
        if not b.valid:
            print(f"  INVALID docs/examples/{b.rel_path}  (docs/{b.doc}:{b.line})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
