#!/usr/bin/env python3
"""Generate godot/assets/ui/theme_pw.tres from tools/blender/palette.json (ART-21, docs/07 s7). Stdlib only.

Every colour comes from palette.json "ui"; sizes from the constants below (min 9 px, target 12 px at 1280x800).
Never hand-edit the .tres; edit palette.json or this script and re-run. `--check` exits 1 when the file is stale.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
PALETTE = REPO / "tools" / "blender" / "palette.json"
OUT = REPO / "godot" / "assets" / "ui" / "theme_pw.tres"
BODY_FONT = "res://assets/ui/fonts/Inter.subset.ttf"
HEAD_FONT = "res://assets/ui/fonts/Rajdhani-SemiBold.subset.ttf"
BODY_SIZE = 12
HEAD_SIZE = 18
SMALL_SIZE = 9
PANEL_ALPHA = 0.78   # docs/07 s7 "ui_bg_1 at 78 %"
STROKE = 2
MARGIN = 8


def col(hexstr: str, alpha: float = 1.0) -> str:
    h = hexstr.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return f"Color({r:.6f}, {g:.6f}, {b:.6f}, {alpha:.6f})"


def box(idx: str, bg: str, border: str, width: int = STROKE) -> list[str]:
    lines = [f'[sub_resource type="StyleBoxFlat" id="{idx}"]', f"bg_color = {bg}", f"border_color = {border}"]
    for side in ("left", "top", "right", "bottom"):
        lines.append(f"border_width_{side} = {width}")
        lines.append(f"content_margin_{side} = {MARGIN}")
    return lines + [""]


def build(palette: dict) -> str:
    u = palette["ui"]
    panel = col(u["ui_bg_1"], PANEL_ALPHA)
    boxes = (
        box("panel", panel, col(u["ui_line"]))
        + box("btn", col(u["ui_bg_2"]), col(u["ui_line"]))
        + box("btn_hover", col(u["ui_bg_2"]), col(u["ui_accent"]))
        + box("btn_pressed", col(u["ui_accent"]), col(u["ui_accent"]))
        + box("btn_disabled", col(u["ui_bg_1"]), col(u["ui_line"]))
        + ["[sub_resource type=\"StyleBoxFlat\" id=\"focus\"]", "draw_center = false", f"border_color = {col(u['ui_focus_on_accent'])}"]
        + [f"border_width_{s} = {STROKE}" for s in ("left", "top", "right", "bottom")] + [""]
    )
    t = ["[gd_resource type=\"Theme\" load_steps=9 format=3]", "",
         "; GENERATED by tools/art/build_theme.py from tools/blender/palette.json. Do not edit by hand.", "",
         f'[ext_resource type="FontFile" path="{BODY_FONT}" id="1"]',
         f'[ext_resource type="FontFile" path="{HEAD_FONT}" id="2"]', ""]
    t += boxes
    t += ["[resource]", "default_font = ExtResource(\"1\")", f"default_font_size = {BODY_SIZE}"]
    text, dim = col(u["ui_text"]), col(u["ui_text_dim"])
    t += [f"Label/colors/font_color = {text}", f"Label/font_sizes/font_size = {BODY_SIZE}",
          f"HeadingLabel/base_type = &\"Label\"", "HeadingLabel/fonts/font = ExtResource(\"2\")",
          f"HeadingLabel/font_sizes/font_size = {HEAD_SIZE}", f"HeadingLabel/colors/font_color = {text}",
          f"DimLabel/base_type = &\"Label\"", f"DimLabel/colors/font_color = {dim}",
          f"DimLabel/font_sizes/font_size = {SMALL_SIZE}",
          "PanelContainer/styles/panel = SubResource(\"panel\")", "Panel/styles/panel = SubResource(\"panel\")",
          "Button/styles/normal = SubResource(\"btn\")", "Button/styles/hover = SubResource(\"btn_hover\")",
          "Button/styles/pressed = SubResource(\"btn_pressed\")",
          "Button/styles/hover_pressed = SubResource(\"btn_pressed\")",
          f"Button/colors/font_pressed_color = {col(u['ui_bg_0'])}",
          f"Button/colors/font_hover_pressed_color = {col(u['ui_bg_0'])}",
          "TabBar/styles/tab_selected = SubResource(\"btn_pressed\")",
          "TabBar/styles/tab_unselected = SubResource(\"btn\")",
          "TabBar/styles/tab_hovered = SubResource(\"btn_hover\")",
          f"TabBar/colors/font_selected_color = {col(u['ui_bg_0'])}",
          f"TabBar/colors/font_unselected_color = {text}",
          f"TabBar/font_sizes/font_size = {BODY_SIZE}","Button/styles/disabled = SubResource(\"btn_disabled\")",
          "Button/styles/focus = SubResource(\"focus\")", f"Button/colors/font_color = {text}",
          f"Button/colors/font_hover_color = {col(u['ui_accent'])}", f"Button/colors/font_disabled_color = {dim}",
          f"Button/colors/font_focus_color = {text}", f"Button/font_sizes/font_size = {BODY_SIZE}",
          f"ProgressBar/colors/font_color = {text}", "ProgressBar/styles/background = SubResource(\"btn_disabled\")",
          f"ProgressBar/font_sizes/font_size = {SMALL_SIZE}", ""]
    return "\n".join(t)


def main() -> int:
    text = build(json.loads(PALETTE.read_text(encoding="utf-8")))
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("theme_pw.tres up to date" if ok else "theme_pw.tres is stale: run tools/art/build_theme.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
