"""Emit the Terrain.height_at / biome_at reference vectors for TA-13 (docs/03 s6.2, s8.3).

    python tools/terrain_vectors.py [MAP_DIR] [--out FILE] [--count N]

Reads the baked u16 / u8 faces with numpy and samples them with the documented bilinear rule, using the numpy
port of the face mapping (tools/moonbake/sphere.py). The sample directions come from a 64-bit LCG with exact
integer-to-double conversion rounded to float32 like Godot's Vector3, so test_terrain.gd regenerates the identical directions without a data file.
Output: height in integer micrometres (round(h * 1e6)) and nearest-texel biome id per direction.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))
from moonbake import sphere as sp  # noqa: E402

LCG_MUL = 6364136223846793005
LCG_ADD = 1442695040888963407
MASK64 = (1 << 64) - 1
SEED = 20260713


def lcg_dirs(seed: int, count: int) -> np.ndarray:
    """count non-unit directions; component = top 24 bits / 2^24 - 0.5 (mirrors test_terrain.gd _dir)."""
    x = seed & MASK64
    out = np.empty((count, 3))
    for i in range(count):
        for k in range(3):
            x = (x * LCG_MUL + LCG_ADD) & MASK64
            out[i, k] = ((x >> 40) & 0xFFFFFF) / 16777216.0 - 0.5
    return out.astype(np.float32).astype(np.float64)   # Godot Vector3 components are float32


def load_faces(map_dir: Path):
    meta = json.loads((map_dir / "meta.json").read_text(encoding="utf-8"))
    n = meta["face_resolution"]
    h = np.stack([np.fromfile(map_dir / f"face{f}.height.u16", dtype="<u2").reshape(n, n) for f in range(6)])
    b = np.stack([np.fromfile(map_dir / f"face{f}.biome.u8", dtype=np.uint8).reshape(n, n) for f in range(6)])
    return n, meta["relief"], h.astype(np.float64), b


def sample(map_dir: Path, dirs: np.ndarray):
    n, relief, h, b = load_faces(map_dir)
    f, u, v = sp.dir_to_face_uv(dirs)
    x, y = u * (n - 1), v * (n - 1)
    ix = np.minimum(np.floor(x).astype(np.int64), n - 2)
    iy = np.minimum(np.floor(y).astype(np.int64), n - 2)
    fx, fy = x - ix, y - iy
    a = h[f, iy, ix] * (1 - fx) + h[f, iy, ix + 1] * fx
    c = h[f, iy + 1, ix] * (1 - fx) + h[f, iy + 1, ix + 1] * fx
    hu = a * (1 - fy) + c * fy
    metres = relief["min_m"] + hu / 65535.0 * (relief["max_m"] - relief["min_m"])
    nx, ny = np.floor(x + 0.5).astype(np.int64), np.floor(y + 0.5).astype(np.int64)
    return metres, b[f, ny, nx]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("map_dir", nargs="?", default=str(REPO / "godot/content/maps/tiny_test"))
    ap.add_argument("--out", default=str(REPO / "godot/test/unit/sim/terrain_vectors.json"))
    ap.add_argument("--count", type=int, default=10000)
    a = ap.parse_args()
    metres, biome = sample(Path(a.map_dir), lcg_dirs(SEED, a.count))
    doc = {"_doc": "Generated by tools/terrain_vectors.py (TA-13); do not edit.", "map": Path(a.map_dir).name,
           "seed": SEED, "count": a.count, "height_um": [int(round(m * 1e6)) for m in metres],
           "biome": [int(x) for x in biome]}
    Path(a.out).write_text(json.dumps(doc, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"{a.count} vectors -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
